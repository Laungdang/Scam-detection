def build_user_message(
    original_input: str,
    input_type: str,
    matched_pattern_names: list[str],
    blacklist_found: bool,
    blacklist_hit_count: int | None = None,
    rag_context: str = "",
    chat_history: list[dict] | None = None,
    pattern_evidence_text: str | None = None,
    history_evidence_text: str | None = None,
) -> str:
    """สร้าง user message ที่ส่งให้ Claude

    หลักการ (ดู CLAUDE.md Section 2.1, 5.2 — Anti-Bias):
    - ส่งเฉพาะ **หลักฐานดิบ** ไม่ส่งคำตัดสินใดๆ
    - ห้ามใส่ "ผลเบื้องต้น", "ระบบประเมิน", "preliminary_status" ในที่ไหนของ prompt
    - Claude เป็นผู้ตัดสิน verdict เอง จาก evidence ที่เห็น
    - blacklist_hit_count ส่งเป็น raw fact — Hard Constraint ใน system prompt ใช้ตัดสิน threshold
    - pattern_evidence_text = คำที่พบต่อมิติ (จาก pattern_service.format_evidence) — ไม่ใช่ label ที่ตีความ
      ถ้าไม่ส่งมา (legacy caller) จะ fallback เป็น matched_pattern_names แบบเดิม
    """
    if pattern_evidence_text:
        patterns_text = pattern_evidence_text
    else:
        patterns_text = (
            "คำสัญญาณที่พบ: " + ", ".join(matched_pattern_names)
            if matched_pattern_names
            else "คำสัญญาณที่พบ: ไม่พบ"
        )
    history_line = f"\n- {history_evidence_text}" if history_evidence_text else ""
    rag_section = f"\n{rag_context}\n" if rag_context else ""
    has_history = bool(chat_history)
    context_note = " [ต่อเนื่องจากการสนทนาก่อนหน้า — พิจารณาหลักฐานสะสมด้วย]" if has_history else ""

    if blacklist_found:
        if blacklist_hit_count is not None:
            blacklist_evidence = f"พบในฐาน blacklist (ถูกรายงาน {blacklist_hit_count} ครั้ง)"
        else:
            blacklist_evidence = "พบในฐาน blacklist (ไม่ทราบจำนวนครั้ง)"
    elif input_type in ("bank_account", "national_id", "fullname"):
        blacklist_evidence = "ตรวจแล้วไม่พบในฐาน blacklist"
    else:
        blacklist_evidence = "ไม่ได้ตรวจ (Blacklist API รองรับเฉพาะเลขบัญชี/บัตรประชาชน/ชื่อ)"

    return f"""{rag_section}ข้อความจากผู้ใช้:{context_note}
"{original_input}"

[หลักฐานที่รวบรวมได้ (ข้อเท็จจริงเท่านั้น ระบบไม่ได้ประเมินอะไรไว้ล่วงหน้า):
- ประเภท input: {input_type}
- ผล blacklist: {blacklist_evidence}{history_line}
- {patterns_text}]

คุณเป็นผู้ตัดสิน verdict (danger/caution/safe) เองจากข้อความ + หลักฐานข้างต้น + บริบทการสนทนา
ปฏิบัติตาม Hard Constraints ใน system prompt อย่างเคร่งครัด (โดยเฉพาะกฎ blacklist hit count)
ตอบเป็น JSON ตามรูปแบบที่กำหนด""".strip()


def _extract_text_from_image(
    client: anthropic.Anthropic,  # noqa: ARG001 — kept for backwards compat, no longer used
    image_base64: str,
    image_media_type: str,
) -> str:
    """ดึงข้อความจากภาพ — ใช้ ocr_service (EasyOCR ก่อน, Claude Vision fallback)

    ai_service ถูกเรียกจาก qa_engine เท่านั้น (Q&A path) → allow_llm_fallback=True
    Rate limit Claude Vision อยู่ใน ocr_service (ดู CLAUDE.md 6.4)
    """
    from app.services.ocr_service import extract_text_from_image
    result = extract_text_from_image(
        image_base64,
        image_media_type=image_media_type,
        allow_llm_fallback=True,
    )
    logger.info(
        f"Image OCR: engine={result.engine_used} chars={result.char_count} "
        f"conf={result.avg_confidence:.2f}"
    )
    return result.text


def analyze_with_ai(
    original_input: str,
    input_type: str,
    matched_pattern_names: list[str],
    blacklist_found: bool,
    blacklist_hit_count: int | None = None,
    chat_history: list[dict] | None = None,
    image_base64: str | None = None,
    image_media_type: str | None = None,
    pattern_evidence_text: str | None = None,
    history_evidence_text: str | None = None,
    skip_rag: bool = False,
) -> dict:
    """skip_rag: caller (qa_engine) ตัดสินว่าไม่ควรดึงเคสคล้าย — เช่น ข้อความไม่มีคำสัญญาณใดๆ
    (ดึงมาก็ได้แต่ scam ที่คล้ายแค่ผิวคำ → anchoring ข้อความปกติ)"""
    if not Settings.CLAUDE_API_KEY:
        logger.warning("Claude API key is not configured.")
        return {
            "success": False,
            "summary_text": None,
            "structured": None,
            "status": "not_configured",
            "message": "ยังไม่ได้ตั้งค่า Claude API key",
        }

    client = anthropic.Anthropic(api_key=Settings.CLAUDE_API_KEY)

    # ถ้ามีภาพ → ดึงข้อความจากภาพก่อน แล้วใช้กับ RAG
    rag_query = original_input
    if image_base64 and image_media_type:
        extracted = _extract_text_from_image(client, image_base64, image_media_type)
        if extracted:
            rag_query = (original_input + "\n" + extracted).strip() if original_input else extracted

    if skip_rag:
        similar_cases = []
        logger.info("RAG skipped (no lexicon signal in input)")
    else:
        similar_cases = retrieve_similar_cases(rag_query)
        rag_summary = [(c["scam_category"], c["similarity"]) for c in similar_cases]
        logger.info(f"RAG retrieved {len(similar_cases)} case(s): {rag_summary}")
    rag_context = build_rag_context(similar_cases)

    current_message = build_user_message(
        original_input=original_input,
        input_type=input_type,
        matched_pattern_names=matched_pattern_names,
        blacklist_found=blacklist_found,
        blacklist_hit_count=blacklist_hit_count,
        rag_context=rag_context,
        chat_history=chat_history,
        pattern_evidence_text=pattern_evidence_text,
        history_evidence_text=history_evidence_text,
    )

    role_map = {"user": "user", "bot": "assistant", "assistant": "assistant"}
    messages = []
    if chat_history:
        for msg in chat_history[-10:]:
            role = role_map.get(msg["role"], "user")
            content = msg["content"] or ""
            if content.strip():
                messages.append({"role": role, "content": content})

    # ถ้ามีภาพ → ส่งเป็น content array (image + text) แทน string ธรรมดา
    if image_base64 and image_media_type:
        logger.info(f"Image attached: media_type={image_media_type}")
        messages.append({
            "role": "user",
            "content": [
                {
                    "type": "image",
                    "source": {
                        "type": "base64",
                        "media_type": image_media_type,
                        "data": image_base64,
                    },
                },
                {
                    "type": "text",
                    "text": (
                        "ภาพนี้ส่งมาเพื่อตรวจสอบมิจฉาชีพ\n"
                        "กรุณาอ่านข้อความทั้งหมดในภาพ แล้ววิเคราะห์ว่ามีสัญญาณมิจฉาชีพหรือไม่\n\n"
                        + current_message
                    ),
                },
            ],
        })
    else:
        messages.append({"role": "user", "content": current_message})

    try:
        logger.info(f"Calling Claude model: {Settings.CLAUDE_MODEL} (history: {len(messages)-1} msgs)")

        message = client.messages.create(
            model=Settings.CLAUDE_MODEL,
            max_tokens=Settings.CLAUDE_MAX_TOKENS,
            system=SYSTEM_PROMPT,
            messages=messages,
        )

        raw = message.content[0].text or ""

        # parse JSON จาก response (รองรับทั้ง raw JSON และ ```json ... ```)
        try:
            text = raw.strip()
            if "```" in text:
                text = text.split("```")[1].strip()
                if text.startswith("json"):
                    text = text[4:].strip()
            start = text.find("{")
            end = text.rfind("}") + 1
            structured = json.loads(text[start:end]) if start != -1 else None
        except Exception as parse_err:
            logger.warning(f"JSON parse failed: {parse_err} | raw={raw[:200]!r}")
            structured = None

        # fallback เป็น plain text ถ้า parse ไม่ได้
        summary_text = structured.get("summary", raw.strip()) if structured else raw.strip()

        return {
            "success": True,
            "summary_text": summary_text,
            "structured": structured,
            "status": "success",
            "message": "AI analysis completed successfully",
        }

    except Exception as e:
        logger.exception("Claude analysis failed.")
        return {
            "success": False,
            "summary_text": None,
            "structured": None,
            "status": "error",
            "message": f"AI analysis failed: {str(e)}",
        }


# backward compatibility
analyze_with_huggingface = analyze_with_ai
